#ifndef LISHI_MONITOR_H
#define LISHI_MONITOR_H
#include <stdint.h>
#define LISHI_MONITOR_MAGIC UINT32_C(0x4c495348)
#define LISHI_MONITOR_ABI_MAJOR 1u
#define LISHI_MONITOR_MAP_BYTES 4096u
enum {
 LISHI_ID=0x00, LISHI_ABI=0x08, LISHI_IMPL=0x10, LISHI_CAPS=0x18,
 LISHI_GEOMETRY=0x20, LISHI_CAPACITY=0x28, LISHI_COUNTER_BITS=0x30,
 LISHI_STATUS=0x38, LISHI_CONTROL=0x40, LISHI_SEQUENCE=0x48,
 LISHI_COUNTER_BASE=0x100, LISHI_SNAPSHOT_STATUS=0x180,
 LISHI_SNAPSHOT_VTYPE=0x188, LISHI_SNAPSHOT_CONFIG=0x190,
 LISHI_SNAPSHOT_ERROR=0x198, LISHI_SNAPSHOT_ADDRESS=0x1a0,
 LISHI_SNAPSHOT_TOKEN_LO=0x1a8,LISHI_SNAPSHOT_TOKEN_HI=0x1b0
};
enum { LISHI_SNAPSHOT=1, LISHI_CLEAR=2, LISHI_SNAPSHOT_VALID=16 };
enum { LISHI_CYCLES, LISHI_BUSY_CYCLES, LISHI_MEMORY_OWNED_CYCLES,
 LISHI_ACCEPTED,LISHI_COMPLETED,LISHI_CANCELED,LISHI_ILLEGAL,
 LISHI_MEMORY_FAULT,LISHI_MEMORY_STOP,LISHI_TL_A,LISHI_TL_D,
 LISHI_COMMAND_STALL,LISHI_COMPLETION_STALL,LISHI_COUNTER_COUNT };
/* 32-bit modular deltas. Sampling interval must remain below one full wrap;
 * cycles wrap after about 14.3 seconds at 300MHz. Recommended interval <=1s.
 * completed means VPU completion handshake, never CPU architectural retire.
 */
static inline uint32_t lishi_counter_delta(uint32_t after,uint32_t before)
{ return after-before; }
#endif
